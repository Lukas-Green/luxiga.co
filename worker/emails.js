const FONT = "'Space Grotesk',-apple-system,BlinkMacSystemFont,'Segoe UI',Arial,Helvetica,sans-serif";

export function escapeHtml(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

// Newline-preserving escape for free-text (messages).
function escapeMultiline(s) {
  return escapeHtml(s).replace(/\n/g, '<br>');
}

// ---------------------------------------------------------------- row helpers
// Each returns a <tr> so callers compose an email body by concatenating rows.

export function pRow(html) {
  return `<tr><td style="padding:0 32px 16px;font:400 16px/1.62 ${FONT};color:${BRAND.ink}">${html}</td></tr>`;
}

export function hRow(text) {
  return `<tr><td style="padding:8px 32px 8px;font:700 17px ${FONT};color:${BRAND.ink}">${escapeHtml(text)}</td></tr>`;
}

// A bordered key/value panel. pairs = [[label, value], ...] (values pre-escaped or plain).
export function panelRow(pairs) {
  const rows = pairs.map(([label, value]) => (
    `<tr>` +
    `<td valign="top" style="padding:5px 14px 5px 0;font:600 13px ${FONT};color:${BRAND.muted};white-space:nowrap">${escapeHtml(label)}</td>` +
    `<td style="padding:5px 0;font:400 15px/1.5 ${FONT};color:${BRAND.ink}">${value}</td>` +
    `</tr>`
  )).join('');
  return `<tr><td style="padding:2px 32px 16px">` +
    `<table role="presentation" cellpadding="0" cellspacing="0" width="100%" style="background:${BRAND.panel};border:1px solid ${BRAND.line};border-radius:12px">` +
    `<tr><td style="padding:14px 18px"><table role="presentation" cellpadding="0" cellspacing="0" width="100%">${rows}</table></td></tr>` +
    `</table></td></tr>`;
}

// A quoted free-text block (the requester's message).
export function quoteRow(text) {
  return `<tr><td style="padding:2px 32px 16px">` +
    `<table role="presentation" cellpadding="0" cellspacing="0" width="100%" style="border-left:3px solid ${BRAND.lime};background:${BRAND.panel};border-radius:0 10px 10px 0">` +
    `<tr><td style="padding:14px 18px;font:400 15px/1.6 ${FONT};color:${BRAND.soft}">${escapeMultiline(text)}</td></tr>` +
    `</table></td></tr>`;
}

export function stepsRow(items) {
  const rows = items.map((it, i) => (
    `<tr>` +
    `<td valign="top" style="padding:0 12px 12px 0;width:30px">` +
    `<div style="width:26px;height:26px;border-radius:50%;background:${BRAND.lime};color:${BRAND.limeInk};font:700 14px ${FONT};text-align:center;line-height:26px">${i + 1}</div></td>` +
    `<td style="padding:0 0 12px;font:400 15px/1.55 ${FONT};color:${BRAND.soft}">${it}</td>` +
    `</tr>`
  )).join('');
  return `<tr><td style="padding:2px 32px 8px"><table role="presentation" cellpadding="0" cellspacing="0" width="100%">${rows}</table></td></tr>`;
}

export function ctaRow(text, href) {
  return `<tr><td style="padding:10px 32px 22px">` +
    `<a href="${href}" style="display:inline-block;background:${BRAND.lime};color:${BRAND.limeInk};font:700 16px ${FONT};text-decoration:none;padding:14px 26px;border-radius:10px">${escapeHtml(text)}</a>` +
    `</td></tr>`;
}

export function signRow(lines) {
  const body = lines.map(escapeHtml).join('<br>');
  return `<tr><td style="padding:8px 32px 6px;font:400 15px/1.6 ${FONT};color:${BRAND.soft}">${body}</td></tr>`;
}

// ---------------------------------------------------------------- layout
