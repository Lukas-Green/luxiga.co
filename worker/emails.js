// To Lukas when someone submits the business-card work-request form.
export function workRequestNotifyHtml(d) {
  const name = d.name || '(no name)';
  const inner = [
    pRow(`<b>New work request</b> just came in through the card.`),
    panelRow([
      ['Name', escapeHtml(name)],
      ['Email', d.email ? `<a href="mailto:${escapeHtml(d.email)}">${escapeHtml(d.email)}</a>` : '(not provided)'],
      ['Phone', d.phone ? escapeHtml(d.phone) : '(not provided)'],
      ['Source', escapeHtml(d.source || 'Card Scan')],
      ['When', escapeHtml(d.when || new Date().toISOString())],
    ]),
    hRow('What they need'),
    quoteRow(d.message || '(no message)'),
    ctaRow('Open the CRM', BRAND.adminUrl),
    d.email ? pRow(`<span style="color:${BRAND.muted};font-size:14px">Reply to this email to respond to ${escapeHtml(name)} directly.</span>`) : '',
  ].join('');
  return wrap({
    title: `New work request — ${name}`,
    preheader: `${name} wants to talk about a project.`,
    inner,
  });
}

// Auto-reply to the person who submitted the work-request form.
export function workRequestReceiptHtml(d) {
  const name = d.name || 'there';
  const inner = [
    pRow(`Hi ${escapeHtml(name)},`),
    pRow(`Thanks for reaching out. I got your note and I'll be in touch shortly — usually within a day.`),
    hRow('What happens next'),
    stepsRow([
      `<b>I read it personally.</b> Your request comes straight to me, not a queue.`,
      `<b>We talk.</b> A quick call or email to understand what you're building and whether I'm the right fit.`,
      `<b>A clear plan.</b> If it's a match, you get a scoped approach and next steps — no pressure.`,
    ]),
    pRow(`In the meantime, feel free to just reply to this email if anything comes up.`),
    signRow(['Talk soon,', `${BRAND.founder}`, `Founder, ${BRAND.company}`, 'luxiga.co']),
  ].join('');
  return wrap({
    title: 'Got your request — LUXIGA',
    preheader: `Thanks ${name} — I got your note and I'll be in touch shortly.`,
    inner,
  });
}

// Weekly digest / follow-up nudge to Lukas. `rows` = panel pairs; `listHtml`
// = optional pre-built HTML block (e.g. the contact list).
export function internalDigestHtml({ title, preheader, headline, statPairs = [], sections = [] }) {
  const parts = [pRow(`<b>${escapeHtml(headline)}</b>`)];
  if (statPairs.length) parts.push(panelRow(statPairs));
  for (const s of sections) {
    parts.push(hRow(s.heading));
    parts.push(`<tr><td style="padding:0 32px 16px;font:400 14px/1.6 ${FONT};color:${BRAND.soft}">${s.html}</td></tr>`);
  }
  parts.push(ctaRow('Open the CRM', BRAND.adminUrl));
  return wrap({ title, preheader, inner: parts.join('') });
}

// The wrapper marketing campaigns render into (the resend provider path).
// `bodyHtml` is the admin-authored campaign body (already HTML). `unsubUrl`
// is the signed one-click link; `postal` satisfies CAN-SPAM.
export function campaignBaseHtml({ subject, preview, bodyHtml, unsubUrl, postal }) {
  const inner = `<tr><td style="padding:0 32px 8px;font:400 16px/1.62 ${FONT};color:${BRAND.ink}">${bodyHtml}</td></tr>`;
  const footerExtraHtml =
    `<div style="font:400 11px/1.6 ${FONT};color:#6a6f5e;padding-top:12px">` +
    `${escapeHtml(postal || `${BRAND.company}`)}<br>` +
    `You're receiving this because you connected with ${escapeHtml(BRAND.company)}.<br>` +
    `<a href="${unsubUrl}" style="color:${BRAND.headMuted};text-decoration:underline">Unsubscribe</a> from these emails.` +
    `</div>`;
  return wrap({
    title: subject || 'LUXIGA',
    preheader: preview || '',
    inner,
    footerExtraHtml,
  });
}

